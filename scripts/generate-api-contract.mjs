#!/usr/bin/env node
/**
 * Generates `src/generated/api-contract.ts` from the committed contract fixture
 * `schema/api.json`.
 *
 * The generated module carries two things that must never disagree:
 *   1. compile-time types the SDK's public surface exposes, and
 *   2. runtime schema descriptors the SDK validates wire payloads against.
 *
 * Run `pnpm gen` to regenerate. `pnpm check:drift` regenerates and fails the
 * build when the committed output no longer matches the schema.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "schema", "api.json");
const outPath = join(root, "src", "generated", "api-contract.ts");

/** @param {{kind: string, [k: string]: unknown}} node */
function tsType(node) {
  const base = baseType(node);
  return node.nullable === true ? `${base} | null` : base;
}

/** @param {{kind: string, [k: string]: unknown}} node */
function baseType(node) {
  switch (node.kind) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "enum":
      return node.values.map((value) => JSON.stringify(value)).join(" | ");
    case "array": {
      const item = tsType(node.items);
      return /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case "ref":
      return node.target;
    default:
      throw new Error(`unsupported schema kind: ${node.kind}`);
  }
}

/** @param {string} name @param {{fields: Record<string, {optional?: boolean}>}} node */
function renderInterface(name, node) {
  if (node.kind !== "object") throw new Error(`type ${name} must be an object`);
  const fields = Object.entries(node.fields).map(
    ([field, spec]) => `  ${field}${spec.optional === true ? "?" : ""}: ${tsType(spec)};`,
  );
  return [`export interface ${name} {`, ...fields, "}"].join("\n");
}

function render(contract) {
  const interfaces = Object.entries(contract.types).map(([name, node]) =>
    renderInterface(name, node),
  );
  return `// Code generated by scripts/generate-api-contract.mjs. DO NOT EDIT BY HAND.
// Source of truth: schema/api.json (${contract.service}, contract ${contract.apiVersion}).
// Regenerate with \`pnpm gen\`; \`pnpm check:drift\` fails when this file is stale.

import type { OperationDescriptor, SchemaNode } from "../schema-types.js";

/** Human-readable name of the upstream service this client speaks to. */
export const SERVICE_NAME = ${JSON.stringify(contract.service)};

/** Contract version the generated types and validators were produced from. */
export const API_VERSION = ${JSON.stringify(contract.apiVersion)};

${interfaces.join("\n\n")}

/** Runtime schema descriptors, used to validate payloads at the wire boundary. */
export const schemas = ${JSON.stringify(contract.types, null, 2)} as const satisfies Record<
  string,
  SchemaNode
>;

/** Name of a type declared by the contract. */
export type SchemaName = keyof typeof schemas;

/** Every operation the contract declares, with its transport shape. */
export const operations = ${JSON.stringify(contract.operations, null, 2)} as const satisfies Record<
  string,
  OperationDescriptor
>;

/** Name of an operation declared by the contract. */
export type OperationName = keyof typeof operations;
`;
}

const contract = JSON.parse(readFileSync(schemaPath, "utf8"));
writeFileSync(outPath, render(contract));
process.stdout.write(`generated ${outPath} from ${schemaPath}\n`);
